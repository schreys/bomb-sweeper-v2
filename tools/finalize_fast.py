"""Finalize levels: pick start/bomb giving the longest shortest-solution, verify solvable, write game/levels.js."""
import json
from collections import deque

ROWS, COLS = 4, 6
MIN_MARGIN = 8.0
STATE_LIMIT = 60000
DIRS = {"U": (-1, 0), "D": (1, 0), "L": (0, -1), "R": (0, 1)}
KEYS = [f"h{r}{c}" for r in range(ROWS + 1) for c in range(COLS)] + \
       [f"v{r}{c}" for r in range(ROWS) for c in range(COLS + 1)]
BIT = {k: 1 << i for i, k in enumerate(KEYS)}


def edge(r, c, dr, dc):
    if dr == -1:
        return f"h{r}{c}"
    if dr == 1:
        return f"h{r + 1}{c}"
    if dc == -1:
        return f"v{r}{c}"
    return f"v{r}{c + 1}"


def is_boundary(key):
    return (key[0] == "h" and key[1] in "04") or (key[0] == "v" and key[2] in "06")


# MOVES[cell] = list of (dir, target cell, edge bit, far bit or 0, edge is boundary)
MOVES = []
for r in range(ROWS):
    for c in range(COLS):
        opts = []
        for d, (dr, dc) in DIRS.items():
            nr, nc = r + dr, c + dc
            if 0 <= nr < ROWS and 0 <= nc < COLS:
                k = edge(r, c, dr, dc)
                opts.append((d, nr * COLS + nc, BIT[k], BIT[edge(nr, nc, dr, dc)], is_boundary(k)))
        MOVES.append(opts)


def bfs(start, walls):
    """Shortest solution string from start cell to every reachable cell (pushes allowed)."""
    s0 = (start, walls)
    parent = {s0: None}
    first = {start: s0}
    q = deque([s0])
    while q and len(parent) < STATE_LIMIT:
        cur = q.popleft()
        pos, w = cur
        for d, tgt, eb, fb, bnd in MOVES[pos]:
            if w & eb:
                if bnd or w & fb:
                    continue
                nw = (w & ~eb) | fb
            else:
                nw = w
            nxt = (tgt, nw)
            if nxt not in parent:
                parent[nxt] = (cur, d)
                first.setdefault(tgt, nxt)
                q.append(nxt)

    def path(state):
        out = []
        while parent[state]:
            state, d = parent[state]
            out.append(d)
        return "".join(reversed(out))

    return {cell: path(st) for cell, st in first.items()}


def main():
    raw = json.load(open("frames/levels_1.json"))
    out, stats = [], {"detected": 0, "chosen": 0, "too_easy": 0}
    for lv in raw:
        on = [k for k, v in lv["walls"].items() if v]
        walls = sum(BIT[k] for k in on)
        detected = lv["bomb"][0] * COLS + lv["bomb"][1] if lv["bomb_margin"] >= MIN_MARGIN else None
        # Start/bomb are not reliably visible in the video: pick the pair with the
        # longest shortest-solution (keeping the bomb when it was clearly detected).
        best = None
        for s in range(ROWS * COLS):
            for b, p in bfs(s, walls).items():
                if detected is not None and b != detected:
                    continue
                if best is None or len(p) > len(best[2]):
                    best = (s, b, p)
        start, bomb, sol = best
        if len(sol) < 4:
            stats["too_easy"] += 1
            continue
        src = "detected" if detected is not None else "chosen"
        stats[src] += 1
        out.append({
            "id": len(out) + 1,
            "source": lv["source_time"],
            "walls": sorted(on),
            "start": [start // COLS, start % COLS],
            "bomb": [bomb // COLS, bomb % COLS],
            "bombSource": src,
            "solution": sol,
            "time": max(15, round(len(sol) * 1.5 + 10)),
        })
    print(stats, "levels:", len(out))
    print("solution lengths:", sorted(len(l["solution"]) for l in out))
    with open("game/levels.js", "w") as f:
        f.write("// Generated by tools/finalize.py from game.mp4\n")
        f.write("window.LEVELS = ")
        json.dump(out, f, separators=(",", ":"))
        f.write(";\n")
    json.dump(out, open("frames/levels_final.json", "w"), indent=1)


if __name__ == "__main__":
    main()
