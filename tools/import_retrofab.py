"""Import the Game A mazes of the RetroFab simulation, verify them and compare with the current levels."""
import json
import sys
from collections import deque

sys.path.insert(0, "tools")
from finalize_fast import BIT, COLS, MOVES  # noqa: E402

DIR_OF = {"h0": "U", "h4": "D", "v0": "L", "v6": "R"}


def checksum(text):
    h = 0
    for ch in text:
        h = (h * 31 + ord(ch)) % 65521
    return h


def exit_cell(k):
    r, c = int(k[1]), int(k[2])
    if k[0] == "h":
        return (0 if r == 0 else 3) * COLS + c
    return r * COLS + (0 if c == 0 else 5)


def solve(start, walls, bombs):
    exits = {}
    for k in bombs:
        exits.setdefault(exit_cell(k), []).append(k)
    s0 = (start, walls)
    parent = {s0: None}
    q = deque([s0])
    while q:
        cur = q.popleft()
        pos, w = cur
        for k in exits.get(pos, []):
            if not w & BIT[k]:
                path = []
                st = cur
                while parent[st]:
                    st, d = parent[st]
                    path.append(d)
                return "".join(reversed(path)) + DIR_OF[k[0] + (k[1] if k[0] == "h" else k[2])]
        for d, tgt, eb, fb, bnd in MOVES[pos]:
            if w & eb:
                if bnd or w & fb:
                    continue
                nw = (w & ~eb) | fb
            else:
                nw = w
            nxt = (tgt, nw)
            if nxt not in parent:
                parent[nxt] = (cur, d)
                q.append(nxt)
    return None


def flip(keys, hor, vert):
    out = set()
    for k in keys:
        r, c = int(k[1]), int(k[2])
        if hor:
            c = (5 - c) if k[0] == "h" else (6 - c)
        if vert:
            r = (4 - r) if k[0] == "h" else (3 - r)
        out.add(f"{k[0]}{r}{c}")
    return out


levels = []
for line in open("tools/retrofab_levels.txt"):
    if not line.strip() or line.startswith("#"):
        continue
    *fields, chk = line.strip().split("|")
    if checksum("|".join(fields)) != int(chk):
        sys.exit(f"checksum mismatch: {line}")
    idx, start, bombs, walls = fields
    r, c = map(int, start.split(","))
    walls = sorted(walls[i:i + 3] for i in range(0, len(walls), 3))
    bombs = bombs.split(",")
    sol = solve(r * COLS + c, sum(BIT[k] for k in walls), bombs)
    if sol is None:
        sys.exit(f"level {idx} unsolvable")
    levels.append({"source": f"retrofab-{idx}", "walls": walls, "start": [r, c], "bombs": bombs, "solution": sol})
print("retrofab levels:", len(levels), "all checksums ok, all solvable")
print("solution lengths:", [len(l["solution"]) for l in levels])

current = json.load(open("frames/levels_final.json"))
print("\nbest match of each RetroFab level among the current levels (walls+bombs differing, any flip):")
matched = set()
for lv in levels:
    a = set(lv["walls"]) | {"B" + b for b in lv["bombs"]}
    best = None
    for cur in current:
        for hor in (0, 1):
            for vert in (0, 1):
                b = flip(cur["walls"], hor, vert) | {"B" + k for k in flip(cur["bombs"], hor, vert)}
                d = len(a ^ b)
                if best is None or d < best[0]:
                    best = (d, cur["id"], cur["source"], hor, vert)
    matched.add(best[1]) if best[0] <= 6 else None
    print(f"  {lv['source']:>12}: diff {best[0]:2d} with level {best[1]:2d} ({best[2]}) flip h={best[3]} v={best[4]}")
print("current levels without a close RetroFab match (diff > 6):",
      [c["id"] for c in current if c["id"] not in matched])
json.dump(levels, open("frames/levels_retrofab.json", "w"), indent=1)

# Game A runs its timer at 50 ticks of 0.5 s.
game_levels = [{"id": i, **lv, "corrected": False, "time": 25} for i, lv in enumerate(levels, 1)]
with open("game/levels.js", "w") as f:
    f.write("// Generated by tools/import_retrofab.py from the RetroFab Game A mazes\nwindow.LEVELS = ")
    json.dump(game_levels, f, separators=(",", ":"))
    f.write(";\n")
print("wrote game/levels.js with", len(game_levels), "levels")
